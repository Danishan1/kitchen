import type { Diet, Difficulty, Recipe, RecipeCategory, Unit } from '../domain/types';

/**
 * Beginner-friendly seed recipes for FIVE servings. Times and costs are estimates —
 * edit any recipe to match how your family actually likes it.
 */
type Ing = [ingredientId: string, qty: number, unit: Unit, note?: string, opts?: { optional?: boolean; sub?: string }];
type Step = string | [text: string, timerMin: number];

interface Def {
  id: string;
  name: string;
  category: RecipeCategory;
  diet: Diet;
  tags: string[];
  prep: number;
  cook: number;
  difficulty: Difficulty;
  ings: Ing[];
  steps: Step[];
  equipment: string[];
  tips: string[];
  mistakes: string[];
  storage: string;
  halal?: string;
  dietaryNotes?: string;
  notes?: string;
  cuisine?: string;
  servings?: number;
}

const SEED_TIME = '2026-01-01T00:00:00.000Z';

function build(d: Def): Recipe {
  return {
    id: d.id,
    name: d.name,
    category: d.category,
    cuisine: d.cuisine ?? 'North Indian home-style',
    tags: d.tags,
    diet: d.diet,
    dietaryNotes: d.dietaryNotes,
    halalNotes: d.halal,
    servings: d.servings ?? 5,
    prepMin: d.prep,
    cookMin: d.cook,
    difficulty: d.difficulty,
    ingredients: d.ings.map(([ingredientId, qty, unit, note, opts], i) => ({
      id: `${d.id}-i${i + 1}`,
      ingredientId,
      qty,
      unit,
      note,
      optional: opts?.optional,
      substitution: opts?.sub,
    })),
    steps: d.steps.map((s, i) =>
      typeof s === 'string' ? { id: `${d.id}-s${i + 1}`, text: s } : { id: `${d.id}-s${i + 1}`, text: s[0], timerMin: s[1] },
    ),
    equipmentIds: d.equipment,
    tips: d.tips,
    mistakes: d.mistakes,
    storage: d.storage,
    notes: d.notes,
    favourite: false,
    timesCooked: 0,
    createdAt: SEED_TIME,
    updatedAt: SEED_TIME,
  };
}

